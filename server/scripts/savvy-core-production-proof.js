#!/usr/bin/env node
/**
 * Savvy Core V1 production proof — server-side runner.
 *
 * Requires:
 *   SAVVY_CORE_PROOF_ENABLED=true
 *   SAVVY_CORE_V1_ENABLED=true
 *   MONGODB_URI
 *   SAVVY_CORE_PROOF_USER_ID or SAVVY_CORE_PROOF_USER_EMAIL
 *
 * Usage:
 *   node scripts/savvy-core-production-proof.js
 */
const path = require('path');
const fs = require('fs');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });

const mongoose = require('mongoose');
const User = require('../models/User');
const { isSavvyCoreProofEnabled } = require('../config/savvyCoreProofConfig');
const { isSavvyCoreEnabled } = require('../config/savvyCoreConfig');
const { runFullProofFlow, PROOF_APP_ID } = require('../services/savvyCore/savvyCoreProofService');
const { resolveDeploymentSha } = require('../config/savvyCoreProofConfig');

const REPORT_PATH = path.join(__dirname, '..', '..', 'SAVVY_CORE_PRODUCTION_PROOF.md');

function fail(msg) {
  console.error(`✗ ${msg}`);
  process.exit(1);
}

function passFail(v) {
  return v ? 'PASS' : 'FAIL';
}

async function resolveTestUser() {
  const id = process.env.SAVVY_CORE_PROOF_USER_ID;
  const email = process.env.SAVVY_CORE_PROOF_USER_EMAIL;
  if (id) {
    const user = await User.findById(id);
    if (!user) fail(`Test user not found: ${id}`);
    return user;
  }
  if (email) {
    const user = await User.findOne({ email: String(email).trim().toLowerCase() });
    if (!user) fail(`Test user not found: ${email}`);
    return user;
  }
  fail('Set SAVVY_CORE_PROOF_USER_ID or SAVVY_CORE_PROOF_USER_EMAIL');
}

function buildReport(result) {
  const r = result.results || {};
  return `# Savvy Core Production Proof

> Auto-generated by \`npm run savvy-core:production-proof\`
> **One-time proof run — do not repeat against production users without a new proofRunId.**

## Deployment

| Field | Value |
|-------|-------|
| DEPLOYMENT SHA | \`${result.deploymentSha || resolveDeploymentSha()}\` |
| TEST USER | \`${result.testUser}\` |
| APP ID | \`${result.appId || PROOF_APP_ID}\` |
| PROOF RUN ID | \`${result.proofRunId}\` |

## Baseline

| Field | Value |
|-------|-------|
| Savvy | ${result.baseline?.savvy ?? '—'} |
| XP | ${result.baseline?.xp ?? '—'} |
| Level | ${result.baseline?.level ?? '—'} |
| Prestige | ${result.baseline?.prestige ?? '—'} |

## Results

| Check | Result |
|-------|--------|
| READ PARITY | ${passFail(r.readParity)} |
| +50 SAVVY | ${passFail(r.savvy50)} |
| FINAL10 BALANCE SYNC | ${passFail(r.final10BalanceSync)} |
| IDEMPOTENCY | ${passFail(r.idempotency)} |
| +25 XP | ${passFail(r.xp25)} |
| FINAL10 XP SYNC | ${passFail(r.final10XpSync)} |
| CONTRACT | ${passFail(r.contract)} |
| COSMETIC | ${passFail(r.cosmetic)} |
| LEDGER APP NAMESPACE | ${passFail(r.ledger)} |
| APP PERMISSIONS (security suite) | ${passFail(r.security)} |
| FINAL PARITY | ${passFail(r.finalParity)} |

## Environment flags used

- \`SAVVY_CORE_PROOF_ENABLED=true\`
- \`SAVVY_CORE_V1_ENABLED=true\`

## Notes

Mock App #2 backend calls Savvy Core services in-process. App keys are never required for this harness path.

Ledger idempotency key pattern: \`savvytrip_test:proof:<proofRunId>:savvy50\`
`;
}

async function main() {
  if (!isSavvyCoreProofEnabled()) {
    fail('SAVVY_CORE_PROOF_ENABLED must be true');
  }
  if (!isSavvyCoreEnabled()) {
    fail('SAVVY_CORE_V1_ENABLED must be true');
  }

  const uri = process.env.MONGODB_URI || 'mongodb://localhost:27017/final10';
  await mongoose.connect(uri);

  const user = await resolveTestUser();
  console.log(`Running Savvy Core production proof for user ${user._id} (${user.username || user.email})`);

  const result = await runFullProofFlow(user);
  const allPass = Object.values(result.results || {}).every(Boolean);

  const report = buildReport(result);
  fs.writeFileSync(REPORT_PATH, report, 'utf8');
  console.log(`\nReport written: ${REPORT_PATH}\n`);
  console.log(report);

  await mongoose.disconnect();
  process.exit(allPass ? 0 : 1);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
